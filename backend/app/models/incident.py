import uuid
from datetime import datetime, timezone
from sqlalchemy import (
    Column,
    String,
    Text,
    Boolean,
    DateTime,
    JSON,
    Uuid,
    Index,
)

from app.database.base import Base


class IncidentStatus:
    ANALYZING = "analyzing"
    AWAITING_CONFIRMATION = "awaiting_confirmation"
    RESOLVED = "resolved"

    ALL_STATUSES = {ANALYZING, AWAITING_CONFIRMATION, RESOLVED}


class Incident(Base):
    __tablename__ = "incidents"

    id = Column(
        Uuid(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
        doc="Unique identifier for the incident",
    )
    incident_code = Column(
        String(64),
        unique=True,
        nullable=False,
        index=True,
        doc="Human-readable unique incident code (e.g. INC-20261107-1234)",
    )
    title = Column(
        String(255),
        nullable=False,
        doc="High-level title of the engineering incident",
    )
    service = Column(
        String(100),
        nullable=False,
        index=True,
        doc="Affected microservice or system component",
    )
    environment = Column(
        String(50),
        nullable=False,
        index=True,
        doc="Deployment environment (e.g. production, staging)",
    )
    error_message = Column(
        Text,
        nullable=False,
        doc="Observed error message or stack trace header",
    )
    logs = Column(
        Text,
        nullable=True,
        doc="Relevant log snippet or trace details",
    )
    ai_diagnosis = Column(
        JSON,
        nullable=True,
        doc="Structured diagnosis generated by Groq SRE model",
    )
    root_cause = Column(
        Text,
        nullable=True,
        doc="Confirmed root cause provided by developer/operator",
    )
    resolution = Column(
        Text,
        nullable=True,
        doc="Verified mitigation and permanent fix implemented",
    )
    status = Column(
        String(50),
        nullable=False,
        default=IncidentStatus.ANALYZING,
        index=True,
        doc="Incident lifecycle status: analyzing, awaiting_confirmation, resolved",
    )
    memory_retained = Column(
        Boolean,
        nullable=False,
        default=False,
        doc="Indicates whether this resolved incident has been persisted in Hindsight Cloud",
    )
    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        doc="Timestamp of incident creation",
    )
    updated_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        doc="Timestamp of last update",
    )
    resolved_at = Column(
        DateTime(timezone=True),
        nullable=True,
        doc="Timestamp when resolution was confirmed and applied",
    )

    __table_args__ = (
        Index("idx_incident_status_created", "status", "created_at"),
        Index("idx_incident_service_env", "service", "environment"),
    )

    def __repr__(self) -> str:
        return f"<Incident {self.incident_code}: {self.title} [{self.status}]>"
